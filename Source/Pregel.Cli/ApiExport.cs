using System.Text;
using System.Text.RegularExpressions;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Heron.Pregel.Cli;

internal static partial class ApiExport
{
    private sealed record Section(string Title, string Directory, string[] Types);

    private static readonly Section[] Sections =
    [
        new("Graph definition and DSL", "Heron.Pregel",
            ["Pregel", "PregelGraphDsl", "PregelLinearGraphDsl", "PregelResultGraphDsl", "PregelMutationDsl", "PregelGraph"]),
        new("Node context, state, expansion and routing", "Heron.Pregel",
            ["PregelNodeContext", "PregelVariable", "PregelMutationItem", "PregelMutationMode", "PregelRetryPolicy",
             "PregelRoute", "MutexRuleAttribute", "PregelSubgraphAttribute"]),
        new("Automation templates", "Heron.Pregel.Automation",
            ["AutomationTemplate", "AutomationGraphTemplateBase", "AutomationGraphTemplate", "AutomationRunResult",
             "AutomationField", "AutomationChoice", "TemplateIdAttribute"]),
    ];

    public static string Export()
    {
        var text = new StringBuilder();
        text.Append("# Heron.Pregel script API (generated)\n\n");
        text.Append("Generated by `heron-pregel api` from the sources of this version. Signatures omit `public`; ")
            .Append("`protected` members are available in derived templates only.\n");
        foreach (var section in Sections)
        {
            var types = Collect(section.Directory, section.Types);
            text.Append("\n## ").Append(section.Title).Append("\n");
            foreach (var name in section.Types)
                foreach (var group in types.Where(t => t.Name == name).GroupBy(t => t.Arity).OrderBy(g => g.Key))
                    AppendType(text, group.ToList());
        }
        return text.ToString();
    }

    private sealed record TypePart(string Name, int Arity, BaseTypeDeclarationSyntax Syntax);

    private static List<TypePart> Collect(string directory, string[] names)
    {
        var wanted = names.ToHashSet(StringComparer.Ordinal);
        var parts = new List<TypePart>();
        var assembly = typeof(ApiExport).Assembly;
        var prefix = $"api/{directory}/";
        foreach (var resource in assembly.GetManifestResourceNames().Where(name => name.Replace('\\', '/').StartsWith(prefix, StringComparison.Ordinal)).OrderBy(name => name, StringComparer.Ordinal))
        {
            using var reader = new StreamReader(assembly.GetManifestResourceStream(resource)!);
            var tree = CSharpSyntaxTree.ParseText(reader.ReadToEnd());
            foreach (var type in tree.GetRoot().DescendantNodes().OfType<BaseTypeDeclarationSyntax>())
            {
                if (type.Parent is BaseTypeDeclarationSyntax || !wanted.Contains(type.Identifier.Text)) continue;
                if (!type.Modifiers.Any(SyntaxKind.PublicKeyword)) continue;
                var arity = type is TypeDeclarationSyntax { TypeParameterList: { } list } ? list.Parameters.Count : 0;
                parts.Add(new(type.Identifier.Text, arity, type));
            }
        }
        return parts;
    }

    private static void AppendType(StringBuilder text, List<TypePart> parts)
    {
        var first = parts[0].Syntax;
        text.Append("\n### ").Append(first.Identifier.Text);
        if (first is TypeDeclarationSyntax { TypeParameterList: { } typeParameters }) text.Append(typeParameters.ToString());
        text.Append("\n\n");
        var summary = parts.Select(p => Summary(p.Syntax)).FirstOrDefault(s => s != null);
        if (summary != null) text.Append(summary).Append("\n\n");
        text.Append("```csharp\n").Append(Declaration(first)).Append('\n');
        foreach (var part in parts)
        {
            if (part.Syntax is EnumDeclarationSyntax enumeration)
                foreach (var member in enumeration.Members) text.Append("    ").Append(member.Identifier.Text).Append('\n');
            if (part.Syntax is not TypeDeclarationSyntax declaration) continue;
            foreach (var member in declaration.Members)
            {
                if (Signature(member, declaration) is not { } signature) continue;
                if (Summary(member) is { } note) text.Append("    // ").Append(note).Append('\n');
                text.Append("    ").Append(signature).Append(signature.EndsWith('}') ? "\n" : ";\n");
            }
        }
        text.Append("```\n");
    }

    private static string Declaration(BaseTypeDeclarationSyntax type)
    {
        var modifiers = string.Join(' ', type.Modifiers.Where(m => !m.IsKind(SyntaxKind.PublicKeyword)
            && !m.IsKind(SyntaxKind.PartialKeyword)).Select(m => m.Text));
        var keyword = type switch
        {
            RecordDeclarationSyntax record => record.ClassOrStructKeyword.IsKind(SyntaxKind.StructKeyword) ? "record struct" : "record",
            EnumDeclarationSyntax => "enum",
            TypeDeclarationSyntax typed => typed.Keyword.Text,
            _ => "type",
        };
        var head = new StringBuilder();
        if (modifiers.Length > 0) head.Append(modifiers).Append(' ');
        head.Append(keyword).Append(' ').Append(type.Identifier.Text);
        if (type is TypeDeclarationSyntax declaration)
        {
            if (declaration.TypeParameterList != null) head.Append(declaration.TypeParameterList);
            if (declaration.ParameterList != null) head.Append(Flatten(declaration.ParameterList.ToString()));
        }
        var bases = type.BaseList?.Types.Select(t => t.Type.ToString()).Where(t => !t.StartsWith("IAutomation", StringComparison.Ordinal)).ToArray();
        if (bases is { Length: > 0 }) head.Append(" : ").Append(string.Join(", ", bases));
        if (type is TypeDeclarationSyntax { ConstraintClauses.Count: > 0 } constrained)
            head.Append(' ').Append(Flatten(string.Join(' ', constrained.ConstraintClauses.Select(c => c.ToString()))));
        return head.ToString();
    }

    private static string? Signature(MemberDeclarationSyntax member, TypeDeclarationSyntax owner)
    {
        var modifiers = member.Modifiers;
        var isPublic = modifiers.Any(SyntaxKind.PublicKeyword);
        var isProtected = modifiers.Any(SyntaxKind.ProtectedKeyword) && !modifiers.Any(SyntaxKind.PrivateKeyword)
            && !modifiers.Any(SyntaxKind.InternalKeyword);
        if (!isPublic && !isProtected) return null;
        if (owner.Modifiers.Any(SyntaxKind.SealedKeyword) && !isPublic) return null;
        SyntaxNode? stripped = member switch
        {
            MethodDeclarationSyntax method when method.ExplicitInterfaceSpecifier is null =>
                method.WithBody(null).WithExpressionBody(null).WithSemicolonToken(default).WithAttributeLists(default),
            ConstructorDeclarationSyntax constructor =>
                constructor.WithBody(null).WithExpressionBody(null).WithInitializer(null).WithSemicolonToken(default).WithAttributeLists(default),
            PropertyDeclarationSyntax property when property.ExplicitInterfaceSpecifier is null =>
                property.WithAttributeLists(default).WithInitializer(null).WithSemicolonToken(default)
                    .WithExpressionBody(null).WithAccessorList(Accessors(property)),
            FieldDeclarationSyntax field when modifiers.Any(SyntaxKind.ConstKeyword) || modifiers.Any(SyntaxKind.StaticKeyword) =>
                field.WithAttributeLists(default).WithSemicolonToken(default),
            _ => null,
        };
        if (stripped is null) return null;
        var signature = Flatten(stripped.WithoutTrivia().ToString());
        signature = AccessorBlock().Replace(signature,
            m => "{ " + string.Join(' ', m.Groups[1].Value.Split(';', StringSplitOptions.RemoveEmptyEntries).Select(a => a.Trim() + ";")) + " }");
        return Regex.Replace(signature, @"^public\s+", "");
    }

    // Shows which accessors exist; expression-bodied properties are read-only.
    private static AccessorListSyntax Accessors(PropertyDeclarationSyntax property)
    {
        if (property.AccessorList is null)
            return SyntaxFactory.AccessorList(SyntaxFactory.SingletonList(
                SyntaxFactory.AccessorDeclaration(SyntaxKind.GetAccessorDeclaration).WithSemicolonToken(SyntaxFactory.Token(SyntaxKind.SemicolonToken))));
        var visible = property.AccessorList.Accessors
            .Where(a => !a.Modifiers.Any(SyntaxKind.PrivateKeyword) && !a.Modifiers.Any(SyntaxKind.InternalKeyword))
            .Select(a => a.WithBody(null).WithExpressionBody(null).WithAttributeLists(default)
                .WithSemicolonToken(SyntaxFactory.Token(SyntaxKind.SemicolonToken)));
        return SyntaxFactory.AccessorList(SyntaxFactory.List(visible));
    }

    private static string Flatten(string value) => WhitespaceRun().Replace(value, " ").Replace("( ", "(").Replace(" )", ")").Trim();

    private static string? Summary(SyntaxNode node)
    {
        var xml = node.GetLeadingTrivia()
            .Select(t => t.GetStructure()).OfType<DocumentationCommentTriviaSyntax>()
            .Select(d => d.ToFullString()).FirstOrDefault();
        if (xml is null) return null;
        var match = SummaryTag().Match(xml);
        if (!match.Success) return null;
        var body = DocLinePrefix().Replace(match.Groups[1].Value, " ");
        // Generic crefs keep their braces until other tags are stripped, so <TInput> survives.
        body = CrefTag().Replace(body, m =>
        {
            var cref = m.Groups[1].Value;
            var paren = cref.IndexOf('(');
            return (paren < 0 ? cref : cref[..paren]).Split('.').Last() + (paren < 0 ? "" : cref[paren..]);
        });
        body = NameTag().Replace(body, "$1");
        body = AnyTag().Replace(body, "").Replace('{', '<').Replace('}', '>');
        var summary = Flatten(System.Net.WebUtility.HtmlDecode(body));
        return summary.Length == 0 ? null : summary;
    }

    [GeneratedRegex(@"\s+")] private static partial Regex WhitespaceRun();
    [GeneratedRegex(@"\{\s*((?:[a-z ]+;\s*)+)\}$")] private static partial Regex AccessorBlock();
    [GeneratedRegex(@"<summary>(.*?)</summary>", RegexOptions.Singleline)] private static partial Regex SummaryTag();
    [GeneratedRegex(@"(?m)^\s*///")] private static partial Regex DocLinePrefix();
    [GeneratedRegex(@"<see\s+cref=""([^""]+)""\s*/>")] private static partial Regex CrefTag();
    [GeneratedRegex(@"<(?:paramref|typeparamref)\s+name=""([^""]+)""\s*/>")] private static partial Regex NameTag();
    [GeneratedRegex(@"<[^>]+>")] private static partial Regex AnyTag();
}
